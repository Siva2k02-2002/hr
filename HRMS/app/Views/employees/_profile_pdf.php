$formatAddress = static function (array $a) use ($val): string {
    if (! $a) {
        return '—';
    }
    $parts = array_filter([
        $a['address_line1'] ?? null, $a['address_line2'] ?? null, $a['city'] ?? null, $a['district'] ?? null,
        $a['state'] ?? null, $a['country'] ?? null,
    ], static fn ($p) => $p !== null && trim((string) $p) !== '');
    $line = esc(implode(', ', $parts));
    if (! empty($a['pincode'])) {
        $line .= ' - ' . esc($a['pincode']);
    }

    return $line !== '' ? $line : '—';
};

// Renders 2 label/value pairs per row.
$pairs = static function (array $items): string {
    $html = '<table class="kv">';
    foreach (array_chunk($items, 2) as $row) {
        $html .= '<tr>';
        foreach ($row as [$label, $value]) {
            $html .= '<td class="k">' . $label . '</td><td class="v">' . $value . '</td>';
        }
        if (count($row) === 1) {
            $html .= '<td class="k"></td><td class="v"></td>';
        }
        $html .= '</tr>';
    }

    return $html . '</table>';
};
