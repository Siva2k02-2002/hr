$date = static function (?string $v): string {
    if (! $v || str_starts_with($v, '0000')) {
        return '—';
    }
    $ts = strtotime($v);

    return $ts ? date('d M Y', $ts) : esc($v);
};
$val   = static fn ($v): string => ($v === null || trim((string) $v) === '') ? '—' : esc((string) $v);
$title = static fn (?string $v): string => ($v === null || $v === '') ? '—' : esc(ucwords(str_replace('_', ' ', $v)));

